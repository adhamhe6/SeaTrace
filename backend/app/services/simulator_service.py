class SimulatorService:
    def __init__(
        self,
        sessionmaker: async_sessionmaker[AsyncSession],
        supervisor: OpcUaSupervisor,
        catalog: Catalog,
        hub: EventHub,
        settings: Settings,
    ) -> None:
        self._sessionmaker = sessionmaker
        self._sup = supervisor
        self._catalog = catalog
        self._hub = hub
        self._s = settings

    def scenarios(self) -> list[ScenarioInfo]:
        return list(SCENARIOS)

    def status(self) -> SimulatorStatus:
        active: list[ActiveScenario] = []
        for item in self._sup.status.active_scenarios:
            active.append(
                ActiveScenario(
                    scenario_id=str(item.get("scenario_id", "")),
                    vessel_code=item.get("vessel_id") or None,
                    started_at=_parse_ts(item.get("started_at")),
                    ends_at=_parse_ts(item.get("ends_at")),
                )
            )
        age = self._sup.heartbeat_age_s()
        return SimulatorStatus(
            connected=self._sup.connected,
            opcua_state=self._sup.status.state,
            endpoint=self._s.opcua_endpoint,
            security=self._s.opcua_security,
            heartbeat=self._sup.status.heartbeat,
            heartbeat_age_s=None if age is None else round(age, 1),
            active_scenarios=active,
            notice=NOTICE,
        )

    async def activate(
        self, scenario_id: str, vessel_code: str | None, duration_s: int | None, actor: str
    ) -> ScenarioResult:
        sc = self._resolve(scenario_id, vessel_code)
        vessel = "" if sc.scope == "server" else (vessel_code or "")
        duration = sc.default_duration_s if duration_s is None else duration_s
        if duration > sc.max_duration_s:
            raise AppError(
                422,
                "invalid_duration",
                f"duration_s must be <= {sc.max_duration_s} for scenario '{scenario_id}'",
            )
        args = [
            ua.Variant(vessel, ua.VariantType.String),
            ua.Variant(scenario_id, ua.VariantType.String),
            ua.Variant(duration, ua.VariantType.UInt32),
        ]
        return await self._command(
            "activate",
            "ActivateScenario",
            scenario_id,
            vessel or None,
            {"duration_s": duration},
            args,
            actor,
        )

    async def clear(self, scenario_id: str, vessel_code: str | None, actor: str) -> ScenarioResult:
        sc = self._resolve(scenario_id, vessel_code)
        vessel = "" if sc.scope == "server" else (vessel_code or "")
        args = [
            ua.Variant(vessel, ua.VariantType.String),
            ua.Variant(scenario_id, ua.VariantType.String),
        ]
        return await self._command(
            "clear", "ClearScenario", scenario_id, vessel or None, {}, args, actor
        )

    async def reset(self, actor: str) -> ScenarioResult:
        return await self._command("reset", "ResetScenarios", None, None, {}, [], actor)

    async def events(self, limit: int) -> list[SimulatorEventOut]:
        async with self._sessionmaker() as session:
            rows = (
                await session.scalars(
                    select(m.SimulatorEvent)
                    .order_by(m.SimulatorEvent.at.desc(), m.SimulatorEvent.id.desc())
                    .limit(limit)
                )
            ).all()
        return [SimulatorEventOut.model_validate(r) for r in rows]

    # ------------------------------------------------------------------ internals
    def _resolve(self, scenario_id: str, vessel_code: str | None) -> ScenarioInfo:
        sc = _BY_ID.get(scenario_id)
        if sc is None:
            raise not_found("Scenario", scenario_id)
        if sc.scope == "vessel":
            if not vessel_code:
                raise AppError(
                    422, "vessel_required", f"Scenario '{scenario_id}' needs a vessel_code"
                )
            if vessel_code not in self._catalog.vessels:
                raise not_found("Vessel", vessel_code)
        return sc

    async def _command(
        self,
        action: str,
        method: str,
        scenario_id: str | None,
        vessel: str | None,
        params: dict[str, Any],
        args: list[ua.Variant],
        actor: str,
    ) -> ScenarioResult:
        started = time.monotonic()
        try:
            out = await self._sup.call_method(method, *args)
        except SimulatorUnavailableError as exc:
            await self._audit(actor, action, scenario_id, vessel, params, "failed", str(exc))
            raise AppError(
                503, "simulator_unavailable", "The simulator is not reachable over OPC UA right now"
            ) from exc
        except Exception as exc:
            await self._audit(actor, action, scenario_id, vessel, params, "failed", repr(exc))
            log.exception("simulator command failed", extra={"method": method})
            raise AppError(
                502, "simulator_error", "The simulator rejected the command at protocol level"
            ) from exc
        accepted = bool(out[0]) if out else False
        message = str(out[1]) if len(out) > 1 else ""
        await self._audit(
            actor,
            action,
            scenario_id,
            vessel,
            params,
            "accepted" if accepted else "rejected",
            message,
        )
        log.info(
            "simulator command",
            extra={
                "action": action,
                "scenario": scenario_id,
                "vessel": vessel,
                "accepted": accepted,
                "ms": round((time.monotonic() - started) * 1000),
            },
        )
        status = self.status()
        self._hub.publish(
            "scenario",
            {
                "action": action,
                "scenario_id": scenario_id,
                "vessel_code": vessel,
                "accepted": accepted,
                "actor": actor,
                "simulator": status.model_dump(mode="json"),
            },
        )
        if not accepted:
            raise AppError(
                409, "scenario_rejected", message or "The simulator rejected the command"
            )
        return ScenarioResult(accepted=True, message=message, simulator=status)

    async def _audit(
        self,
        actor: str,
        action: str,
        scenario_id: str | None,
        vessel: str | None,
        params: dict[str, Any],
        result: str,
        message: str,
    ) -> None:
        try:
            async with self._sessionmaker() as session, session.begin():
                session.add(
                    m.SimulatorEvent(
                        actor=actor,
                        action=action,
                        scenario_id=scenario_id,
                        vessel_code=vessel,
                        params=params or None,
                        result=result,
                        message=message[:1000],
                    )
                )
        except Exception:
            log.exception("failed to write simulator audit event")


def _parse_ts(value: Any) -> datetime | None:
    if not isinstance(value, str) or not value:
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(UTC)
    except ValueError:
        return None
